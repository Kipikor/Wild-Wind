using UnityEngine;

public class ShipClaudiumLoop : MonoBehaviour
{
    [Header("Геометрия и Емкость")]
    public string названиеКонтура = "Клавдиевый контур";
    public float объемСистемыЛ = 50f;         // Полный объем труб (л)
    public float длинаКонтураМ = 25f;         // Общая длина труб (м)
    
    [Header("Состояние раствора")]
    public float концентрацияКлавдия = 10f;    // Текущая концентрация (%)
    public float целеваяКонцентрация = 10f;    // К чему стремится авто-фидер
    public float запасРаствораЛ = 100f;        // Объем воды (не меняется)
    public float плотностьРаствора = 1.2f;     // кг/л
    
    [Header("Кристаллы Клавдия")]
    public float запасКристалловКг = 5.0f;     // Запас сухого вещества
    public float скоростьРастворения = 0.5f;   // кг/мин
    
    [Header("Тепловой режим (Анти-нагрев)")]
    public float текущаяТемпература = 20f;     // Градусы Цельсия
    public float внешнийПодогревВт = 0f;       // Тепло от печи (ручное)
    public bool забиратьТеплоОтДвигателя = true; 
    public float теплоОтДвигателяВт = 0f;      // Сколько реально пришло от мотора
    public float коэфТеплопотери = 0.05f;      // Потеря тепла в атмосферу
    public bool замерз = false;                // Флаг блокировки системы

    [Header("Динамика и Давление")]
    public float скоростьПотока_мс = 0f;       
    public float текущееДавлениеБар = 0f;      
    public float максДавлениеБар = 200f;       
    public float кпдКонтура = 0.85f;           
    
    [Header("Выход газа")]
    public ShipBalloon выходнойБаллон;         

    [Header("Справочно (Телеметрия)")]
    public float создаваемаяСилаН = 0f;        
    public float трениеОПространствоН = 0f;    

    public void UpdatePhysics(float enginePowerWatts, float deltaTime)
    {
        float массаВКонтуре = объемСистемыЛ * плотностьРаствора;
        
        // 1. Проверка на замерзание (лед блокирует движение)
        if (текущаяТемпература <= 0) 
        {
            замерз = true;
            скоростьПотока_мс = Mathf.Lerp(скоростьПотока_мс, 0, deltaTime * 5f);
        }
        else
        {
            замерз = false;
        }

        // 2. Расчет Сил Сопротивления (Трение)
        float активныйКлавдийКг = массаВКонтуре * (концентрацияКлавдия / 100f);
        
        // Эфирное трение (Drag пространства)
        трениеОПространствоН = замерз ? 0 : 2.6f * активныйКлавдийКг * (скоростьПотока_мс * скоростьПотока_мс) * длинаКонтураМ;
        
        // Гидравлическое трение (Вязкость)
        float трениеГидравликаН = 0.5f * массаВКонтуре * (скоростьПотока_мс * скоростьПотока_мс) * (1f / длинаКонтураМ);
        if (замерз) трениеГидравликаН = 5000f; // Лед стоит колом

        float суммарноеСопротивлениеН = трениеОПространствоН + трениеГидравликаН;

        // 3. Динамика Потока (F = m * a)
        // Сила насоса: P = F * v => F = P / v
        float эффективнаяМощностьВт = enginePowerWatts * кпдКонтура;
        float силаНасосаН = 0f;
        
        if (!замерз && эффективнаяМощностьВт > 0)
        {
            // Используем v + 0.1 чтобы избежать деления на ноль при старте
            силаНасосаН = эффективнаяМощностьВт / (Mathf.Max(скоростьПотока_мс, 0.5f));
            
            // Лимитируем силу насоса, чтобы трубы не лопнули при старте
            силаНасосаН = Mathf.Min(силаНасосаН, максДавлениеБар * 100f); 
        }

        // Ускорение потока: (Сила_насоса - Сопротивление) / Инерционная_Масса
        // Умножаем на 2.0, чтобы учесть инерцию самого насоса и маховиков
        float ускорениеПотока = (силаНасосаН - суммарноеСопротивлениеН) / (массаВКонтуре * 2.0f);
        
        // Интегрируем скорость
        скоростьПотока_мс += ускорениеПотока * deltaTime;
        скоростьПотока_мс = Mathf.Max(0, скоростьПотока_мс);

        // 4. Подъемная сила (Зависит от текущей СКОРОСТИ, а не от оборотов двигателя напрямую)
        создаваемаяСилаН = активныйКлавдийКг * скоростьПотока_мс * длинаКонтураМ * 17.0f;

        // 5. Давление и Расход (как раньше)
        текущееДавлениеБар = (суммарноеСопротивлениеН / 100f) + (скоростьПотока_мс * 0.5f);
        
        float расходКлавдияКг = (создаваемаяСилаН / 1000000f) * deltaTime;
        
        float потеряПроцентов = (расходКлавдияКг / массаВКонтуре) * 100f;
        концентрацияКлавдия = Mathf.Max(0, концентрацияКлавдия - потеряПроцентов);

        if (выходнойБаллон != null && выходнойБаллон.gameObject.activeSelf)
        {
            выходнойБаллон.текущийГазКг += расходКлавдияКг;
        }

        // 6. Кристаллы и Тепло (как раньше)
        if (!замерз && концентрацияКлавдия < целеваяКонцентрация && запасКристалловКг > 0)
        {
            float нужнаяМасса = (целеваяКонцентрация - концентрацияКлавдия) / 100f * массаВКонтуре;
            float добавляем = Mathf.Min(нужнаяМасса, (скоростьРастворения / 60f) * deltaTime);
            запасКристалловКг -= добавляем;
            концентрацияКлавдия += (добавляем / массаВКонтуре) * 100f;
        }

        // 7. ТЕПЛОВОЙ БАЛАНС (АНТИ-НАГРЕВ)
        float мощностьОхлажденияВт = трениеОПространствоН * скоростьПотока_мс;
        float теплоемкость = массаВКонтуре * 4200f; // Вода
        
        float потеряТемпературы = (мощностьОхлажденияВт / теплоемкость) * deltaTime;
        
        // Суммируем тепло: ручной подогрев + от двигателя
        float итоговыйПритокВт = внешнийПодогревВт;
        if (забиратьТеплоОтДвигателя) итоговыйПритокВт += теплоОтДвигателяВт;
        
        float притокТепла = (итоговыйПритокВт / теплоемкость) * deltaTime;
        
        // Теплообмен (стремится к +20). Коэффициент 0.1 для плавности.
        float теплообмен = (текущаяТемпература - 20f) * 0.1f * deltaTime;
        
        // Используем множитель 5х для заметности в игре
        текущаяТемпература += (притокТепла * 5f) - (потеряТемпературы * 5f) - теплообмен;
    }

    public float GetRequiredPowerWatts()
    {
        // Суммарная мощность на преодоление всех видов трения
        // P = F * v
        float массаВКонтуре = объемСистемыЛ * плотностьРаствора;
        float трениеГидравликаН = 0.5f * массаВКонтуре * (скоростьПотока_мс * скоростьПотока_мс) * (1f / длинаКонтураМ);
        
        float totalFrictionForce = трениеОПространствоН + трениеГидравликаН;
        return (totalFrictionForce * скоростьПотока_мс) / кпдКонтура;
    }
}
